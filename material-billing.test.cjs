const assert=require('node:assert/strict'),core=require('./plotter-core');
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,a+' != '+b);
const quote={product:0,qty:1,width:22.5,height:300,price:21,billingBasis:'surface'};
near(core.calculate(quote).total,14.175);
const waste=core.calculate({...quote,billingBasis:'consumed',rollWidth:100});
near(waste.area,.675);near(waste.billedArea,3);near(waste.wasteArea,2.325);near(waste.total,63);
near(core.calculate({...quote,width:300,height:22.5,billingBasis:'consumed',rollWidth:100}).total,63);
near(core.calculate({...quote,width:25,billingBasis:'surface'}).total,15.75);
near(core.calculate({...quote,width:25,billingBasis:'consumed',rollWidth:100}).total,63);
near(core.calculate({...quote,qty:4,billingBasis:'consumed',rollWidth:100}).billedArea,3);
near(core.calculate({...quote,billingBasis:'consumed',rollWidth:100,laminate:true,lamPrice:18}).total,117);
const pvc=core.products.findIndex(p=>p.name==='Vinilo + PVC 5 mm');
const board=core.calculate({product:pvc,qty:3,width:40,height:60,price:60,billingBasis:'consumed',stockSource:'sheet',rollWidth:100,stockHeight:200});
near(board.billedArea,2);near(board.total,120);assert.equal(board.sheets,1);
near(core.calculate({...quote,billingBasis:'consumed',rollWidth:120}).billedArea,3.6);
assert.throws(()=>core.calculate({...quote,billingBasis:'consumed',rollWidth:0}),/ancho/);
assert.throws(()=>core.calculate({...quote,billingBasis:'consumed',rollWidth:10}),/no cabe/);
assert.throws(()=>core.calculate({...quote,billingBasis:'consumed',stockSource:'sheet',rollWidth:100,stockHeight:20}),/no cabe/);
assert.equal(core.calculate({...quote,billingBasis:'surface',rollWidth:0}).total,core.calculate({...quote,billingBasis:undefined}).total);
console.log('Surface/whole-roll billing, 3000×225/250 mm examples, repeat quantities, lamination, whole sheets, invalid stock and old prices passed');
